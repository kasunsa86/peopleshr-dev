async function init() {
  try {
    const data = WEBINAR_DATA;

    const body = document.getElementById('wb-body');
    const hasUpcoming = data.upcoming && data.upcoming.length > 0;
    // Featured webinar drops off by itself once its start time has passed
    const featured = data.featured && new Date(data.featured.date) > new Date() ? data.featured : null;
    body.innerHTML =
      (featured ? renderFeatured(featured) : '') +
      (hasUpcoming ? renderUpcoming(data.upcoming) : (featured ? '' : renderComingSoon())) +
      renderRecordings(data.recordings) +
      renderCTA();

    if (featured) startCountdown(featured.date);

    // Wire up video + gate modals
    renderModal();
    renderGateModal();
    document.getElementById('wb-body').addEventListener('click', e => {
      const recCard = e.target.closest('.wb-rec-card[data-ytid]');
      if (!recCard) return;
      if (recCard.dataset.gated) {
        openGateModal(recCard.dataset.ytid, recCard.dataset.title);
      } else {
        openVideoModal(recCard.dataset.ytid, recCard.dataset.title);
      }
    });

    // Kick off interactive features after DOM is ready
    initSlider();
    initReveal();
    initHamburger();
    window.addEventListener('resize', () => { upcomingIndex = 0; initSlider(); });

  } catch (err) {
    document.getElementById('wb-body').innerHTML = `
      <div style="text-align:center;padding:80px 20px;color:#6b7280;">
        <p style="font-size:1.1rem;font-weight:600;color:#ef4444;margin-bottom:8px;">Could not load webinar data</p>
        <p style="font-size:.9rem;">${err.message}</p>
      </div>`;
    console.error('Webinar page error:', err);
  }
}

init();